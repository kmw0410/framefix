import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
const browser = await chromium.launch({headless:true});
try {
  const context = await browser.newContext({ viewport: {width:390,height:520} });
  const messages = JSON.parse(await readFile('i18n/ko/messages.json','utf8'));
  await context.addInitScript(({messages}) => {
    window.chrome = {
      i18n:{getMessage:key=>messages[key]?.message ?? '',getUILanguage:()=> 'ko'},
      storage:{local:{get:async()=>({settings:JSON.parse(localStorage.getItem('settings') ?? 'null')}),set:async value=>localStorage.setItem('settings',JSON.stringify(value.settings))}}
    };
  }, {messages});
  await context.route('https://extension.test/**', async route => {
    const file = new URL(route.request().url()).pathname.slice(1) || 'popup.html';
    await route.fulfill({body:await readFile(`dist/chrome/${file}`),contentType:file.endsWith('.css')?'text/css':file.endsWith('.js')?'text/javascript':'text/html'});
  });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  await page.emulateMedia({colorScheme:'dark'});
  await page.goto('https://extension.test/popup.html');
  await page.waitForFunction(()=>!document.querySelector('#quality').disabled);
  assert.equal(await page.locator('html').getAttribute('data-theme'),'system');
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='Changes are saved automatically.');
  assert.equal(await page.locator('html').getAttribute('lang'), 'en');
  assert.equal(await page.locator('#quality-label').textContent(), 'Playback quality');
  await page.locator('#quality').click();
  assert.equal(await page.getByRole('option', {name:'Auto',exact:true}).count(), 0);
  await page.keyboard.press('Escape');
  await page.reload();
  await page.waitForFunction(()=>document.documentElement.lang==='en' && !document.querySelector('#quality').disabled);
  assert.equal(await page.getByRole('button',{name:'English',exact:true}).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button',{name:'한국어',exact:true}).click();
  await page.waitForFunction(()=>document.documentElement.lang==='ko');
  await page.locator('[data-language="auto"]').click();
  await page.waitForFunction(()=>JSON.parse(localStorage.settings).language==='auto');
  assert.equal(await page.locator('html').getAttribute('lang'), 'ko');
  console.log('PASS: language switches immediately, translates dropdown, persists across reload and restores browser language');
  const bg = () => page.locator('body').evaluate(el=>getComputedStyle(el).backgroundColor);
  assert.equal(await bg(),'rgb(25, 25, 25)');
  await page.emulateMedia({colorScheme:'light'});
  assert.equal(await bg(),'rgb(250, 250, 249)');
  await page.getByRole('button',{name:'다크 모드',exact:true}).click();
  assert.equal(await bg(),'rgb(25, 25, 25)');
  await page.reload();
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark');
  await page.locator('#enhanced').check();
  await page.locator('#enabled').uncheck();
  assert.equal(await page.locator('#enhanced').isDisabled(),true);
  assert.equal(await page.locator('#quality').isDisabled(),true);
  assert.equal(await page.locator('#quality').evaluate(el=>el.value),'1080');
  await page.waitForFunction(()=>JSON.parse(localStorage.settings).enabled===false);
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#enabled').disabled);
  assert.equal(await page.locator('#enabled').isChecked(),false);
  assert.equal(await page.locator('#quality').isDisabled(),true);
  assert.equal(await page.locator('#enhanced').isChecked(),true);
  assert.equal(await page.getByRole('button',{name:'English',exact:true}).isEnabled(),true);
  await page.locator('#enabled').check();
  assert.equal(await page.locator('#quality').isEnabled(),true);
  assert.equal(await page.locator('#enhanced').isChecked(),true);
  await page.locator('#enhanced').check();
  await page.waitForFunction(()=>JSON.parse(localStorage.settings).preferEnhancedBitrate===true);
  await page.locator('#quality').focus();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Home');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#quality').evaluate(el=>el.value), '1080');
  assert.equal(await page.locator('#quality').getAttribute('aria-expanded'), 'false');
  await page.keyboard.press('Enter');
  await page.keyboard.press('Home');
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#quality').evaluate(el=>el.value), '240');
  await page.keyboard.press('Enter');
  await page.keyboard.type('1080');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#quality').evaluate(el=>el.value), '1080');
  await page.locator('#quality').click();
  await page.keyboard.press('Tab');
  assert.equal(await page.locator('#quality').getAttribute('aria-expanded'), 'false');
  await page.locator('#quality').click();
  await page.locator('.wordmark').click();
  assert.equal(await page.locator('#quality').getAttribute('aria-expanded'), 'false');
  console.log('PASS: custom dropdown pointer, keyboard selection, typeahead, Escape, Tab and outside click');
  await mkdir('artifacts',{recursive:true});
  await page.locator('body').screenshot({path:'artifacts/popup-dark.png',animations:'disabled'});
  await page.getByRole('button',{name:'라이트 모드',exact:true}).click();
  await page.locator('body').screenshot({path:'artifacts/popup-light.png',animations:'disabled'});
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export-settings').click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'framefix-settings.json');
  const exported = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.equal(exported.app, 'framefix');
  assert.equal(exported.version, 2);
  assert.equal(exported.settings.enabled, true);
  assert.equal(exported.settings.quality, '1080');
  const backup = JSON.stringify({app:'framefix',version:1,settings:{quality:'720',theme:'dark',preferEnhancedBitrate:false}});
  const upload = text => page.locator('#settings-file').setInputFiles({name:'settings.json',mimeType:'application/json',buffer:Buffer.from(text)});
  await upload(backup);
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='설정을 가져와 적용했습니다.');
  assert.equal(await page.locator('#quality').evaluate(el=>el.value), '720');
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  const saved = await page.evaluate(()=>localStorage.settings);
  await upload('{bad json');
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='올바른 FrameFix 설정 파일이 아닙니다.');
  assert.equal(await page.evaluate(()=>localStorage.settings), saved);
  await upload(backup.replace('"version":1','"version":3'));
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='지원하지 않는 설정 파일 버전입니다.');
  assert.equal(await page.evaluate(()=>localStorage.settings), saved);
  await page.evaluate(()=>{chrome.storage.local.set=async()=>{throw new Error('storage failure');};});
  await upload(backup.replace('720','2160'));
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='저장하지 못했습니다. 다시 변경해 주세요.');
  assert.equal(await page.locator('#quality').evaluate(el=>el.value), '720');
  assert.equal(await page.evaluate(()=>localStorage.settings), saved);
  assert.equal(await page.locator('#import-settings').isEnabled(), true);
  console.log('PASS: JSON download, import, invalid/version rejection and storage-failure rollback');
  await page.evaluate(()=>{chrome.storage.local.set=async value=>localStorage.setItem('settings',JSON.stringify(value.settings));});
  await page.getByRole('button',{name:'다크 모드',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent==='변경 사항은 자동으로 저장됩니다.');
  await page.locator('#quality').click();
  await page.locator('body').screenshot({path:'artifacts/quality-dropdown-dark.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'라이트 모드',exact:true}).click();
  await page.locator('#quality').click();
  await page.locator('body').screenshot({path:'artifacts/quality-dropdown-light.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  assert.deepEqual(errors,[]);
  console.log('PASS: popup translation, system theme changes, explicit theme, persistence, quality and bitrate controls');

  const playerPage = await browser.newPage();
  await playerPage.route('https://www.youtube.com/**', route=>route.fulfill({contentType:'text/html',body:'<div id="movie_player"></div>'}));
  await playerPage.goto('https://www.youtube.com/watch?v=test');
  await playerPage.evaluate(()=>{
    const p=document.querySelector('#movie_player');
    window.calls=[];window.current='hd1080';
    p.getAvailableQualityLevels=()=>['hd2160','hd1080','hd1080_premium','medium'];
    p.getPlaybackQuality=()=>window.current;
    p.setPlaybackQualityRange=(min,max)=>window.calls.push([min,max]);
    p.setPlaybackQuality=id=>window.current=id;
  });
  await playerPage.addScriptTag({content:await readFile('dist/chrome/player.js','utf8')});
  const configure = settings=>playerPage.evaluate(settings=>window.postMessage({channel:'youtube-auto-hd',type:'settings',settings},location.origin),settings);
  await configure({quality:'1080',preferEnhancedBitrate:false});
  await playerPage.waitForFunction(()=>window.calls.length===1);
  assert.deepEqual(await playerPage.evaluate(()=>window.calls[0]),['hd1080','hd1080']);
  await configure({quality:'1080',preferEnhancedBitrate:true});
  await playerPage.waitForFunction(()=>window.current==='hd1080_premium');
  await configure({enabled:false,quality:'1080',preferEnhancedBitrate:true});
  await playerPage.waitForFunction(()=>window.current==='auto');
  await playerPage.evaluate(()=>{window.current='medium'; document.dispatchEvent(new Event('loadedmetadata'));});
  assert.equal(await playerPage.evaluate(()=>window.current),'medium');
  await configure({enabled:true,quality:'1080',preferEnhancedBitrate:true});
  await playerPage.waitForFunction(()=>window.current==='hd1080_premium');
  await configure({enabled:false,quality:'1080',preferEnhancedBitrate:true});
  await playerPage.waitForFunction(()=>window.current==='auto');
  await playerPage.evaluate(()=>document.querySelector('#movie_player').classList.add('ad-showing'));
  await configure({quality:'2160'});
  assert.equal(await playerPage.evaluate(()=>window.current),'auto');
  await playerPage.evaluate(()=>document.querySelector('#movie_player').classList.remove('ad-showing'));
  await playerPage.waitForFunction(()=>window.current==='hd2160');
  console.log('PASS: mocked player locks initially matching quality, selects exposed Premium, restores auto, skips ads and reapplies');
} finally { await browser.close(); }
